def _render(text):
    text = text.upper()
    lines = ["", "", "", "", ""]
    for ch in text:
        glyph = _FONT.get(ch, _FONT["?"])
        w = max(len(g) for g in glyph)
        for i, g in enumerate(glyph):
            lines[i] += g.ljust(w) + " "
    return [l.rstrip() for l in lines]

def big(text, fg=None, gradient=None, align="left", width=None, small=False):
    # small=False игнорируется, оставлен для обратной совместимости
    lines = _render(text)
    if width:
        from .text import align as _a
        lines = [_a(l, width, align) for l in lines]
        
    if gradient:
        if isinstance(gradient, str):
            colors = GRADIENTS.get(gradient.lower(), GRADIENTS["default"])
        else:
            colors = gradient
        return "\n".join(multi_gradient(l, list(colors)) for l in lines)
        
    if fg:
        return "\n".join(colorize(l, fg=fg) for l in lines)
        
    return "\n".join(lines)

def banner(text, subtitle=None, style="double", fg=None, bg=None, width=None, gradient=None, small=False):
    """Крупный центрированный заголовок с рамкой."""
    from .boxes import box
    if gradient:
        if isinstance(gradient, str):
            colors = GRADIENTS.get(gradient.lower(), GRADIENTS["default"])
        else:
            colors = gradient
        lines = _render(text)
        rendered_text = "\n".join(multi_gradient(l, list(colors)) for l in lines)
        if subtitle:
            sub_color = fg_hex(colors[0]) if not fg else fg
            rendered_text += "\n\n" + colorize(subtitle, fg=sub_color)
        return box(rendered_text, style=style, border_fg=fg, bg=bg, padding=2, width=width, align_mode="center")
    else:
        lines = [text]
        if subtitle:
            lines.append(subtitle)
        return box(lines, style=style, border_fg=fg, bg=bg, padding=2, width=width, align_mode="center")